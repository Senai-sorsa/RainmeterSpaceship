#!/usr/bin/env python3
"""Build the cockpit (Skins/Spaceship/Frame) as Rainmeter Shape meters, symmetric left/right.

The windows come from the owner's line drawing (tools/ref_layout.py WINDOWS). Everything else is designed
here on the left side and mirrored, in the spirit of a real sci-fi cockpit render: gunmetal panels with
cylindrical shading, window frames with gaskets and bolts, lit sills, side walls with grab handles and
blue LED clusters, a centre console with a hologram projector well, corrugated hoses, and recessed
housings behind every instrument that sits on the hull.

Parts written to Frame/Parts (drawing order, see Frame.ini, generated too):
  Glass, Glare, Scan        theme-tinted glass, reflections, optional scanlines        (always)
  Hull                      silhouette + shaded structural panels                      (vector mode)
  [ShipImage]               picture mode, Settings UseShipImage=1 (tools/image_frame.py)
  Frames, Greebles, Lights  window frames, surface detail, strut lights + LEDs         (vector mode)
  Housings, Spill, Decor    instrument housings, HUD light on the dash, HUD lines      (always)

Metal tones are variables (Settings.inc HullDark / HullMid / HullLight / HullEdge), so the shading can be
retuned without regenerating. Usage: python tools/ship_frame.py
"""
