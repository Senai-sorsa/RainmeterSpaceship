#!/usr/bin/env python3
"""Build the cockpit (Skins/Spaceship/Frame), symmetric left/right.

The windows come from the owner's line drawing (tools/ref_layout.py WINDOWS). Everything else is designed
here on the left side and mirrored, in the spirit of a real sci-fi cockpit render: gunmetal struts with
rounded shading, window frames with gaskets and bolts, lit sills, side walls with grab handles and blue LED
banks, a centre console with a hologram projector well, corrugated floor hoses.

Two outputs:
  baked  the neutral metal (Hull, Frames, Greebles) -> tools/frame_src, rasterised and textured by
         tools/frame_render.py into @Resources/Images/hull.png (+ window_mask, glass_fx, scan, shade)
  live   Shape meters in Frame/Parts that must follow the colour theme: Glass (tint), Accents (rim glow,
         LEDs, hazard marks pulled out of the baked layers), Spill, Lights, Decor (HUD lines)
Frame.ini's drawing order is regenerated too.

Metal tones are Settings.inc variables (HullDark / HullMid / HullLight / HullEdge), read when baking.
Usage: python tools/ship_frame.py
"""
