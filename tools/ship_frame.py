ROOT = Path(__file__).resolve().parent.parent
PARTS = ROOT / "Skins" / "Spaceship" / "Frame" / "Parts"
FRAME_INI = PARTS.parent / "Frame.ini"
SRC_PARTS = ROOT / "tools" / "frame_src" / "Parts"
CW, CH = R.CW, R.CH
PER_METER = 150
HEADER = "; GENERATED by tools/ship_frame.py - edit the generator, not this file.\n"

DARK, MID, LIGHT, EDGE = "#HullDark#", "#HullMid#", "#HullLight#", "#HullEdge#"
ACC = "#ColorAccent#"
VECTOR_ONLY = "#UseShipImage#"


# ------------------------------------------------------------------ geometry helpers
def C(pts):
    """reference px -> canvas px"""
    return [(x * R.SX, y * R.SY) for x, y in pts]


def cpoly(pts):
    return Polygon(C(pts)).buffer(0)


def mirror(geom):
    return shp_scale(geom, -1, 1, origin=(CW / 2, 0))


def mpts(pts):
    return [(CW - x, y) for x, y in pts]


def polys_of(g):
    if g.is_empty:
        return []
    if isinstance(g, Polygon):
        return [g]
    return [p for p in getattr(g, "geoms", []) if isinstance(p, Polygon)]


def lines_of(g):
    if g.is_empty:
        return []
    if isinstance(g, LineString):
        return [g]
    if isinstance(g, MultiLineString):
        return list(g.geoms)
    out = []
    for p in getattr(g, "geoms", []):
        out += lines_of(p)
    return out


def hole_free(poly, depth=0):
    """Rainmeter paths have no holes: split polygons with interiors until none remain"""
    if not poly.interiors or depth > 12:
        return [Polygon(poly.exterior)]
    x = poly.interiors[0].centroid.x
    minx, miny, maxx, maxy = poly.bounds
    out = []
    for p in polys_of(split(poly, LineString([(x, miny - 1), (x, maxy + 1)]))):
        out += hole_free(p, depth + 1)
    return out


def norm(vx, vy):
    l = math.hypot(vx, vy) or 1.0
    return vx / l, vy / l


def at(A, B, t):
    return (A[0] + (B[0] - A[0]) * t, A[1] + (B[1] - A[1]) * t)


def grad(angle, *stops):
    return f"{angle:.0f} | " + " | ".join(f"{c} ; {o:.2f}" for c, o in stops)


# ------------------------------------------------------------------ output
class Layer:
    """Shapes for one part file, split over meters of PER_METER shapes. '{G}' in a spec is replaced by the
    shape's own gradient option name."""

    def __init__(self, name, hidden=None, redirect=None):
        # redirect: baked (neutral metal) layers hand their theme-coloured shapes to a live layer
        self.name, self.hidden, self.items, self.redirect = name, hidden, [], redirect

    def _add(self, item):
        live = self.redirect is not None and any(t in item[2] for t in (ACC, "#ColorWarn#"))
        (self.redirect.items if live else self.items).append(item)

    def path(self, pts, spec, closed=False, gradient=None):
        if len(pts) < 2:
            return
        d = " | ".join(("%.1f,%.1f" if i == 0 else "LineTo %.1f,%.1f") % p for i, p in enumerate(pts))
        if "Fill " not in spec:
            spec = "Fill Color 0,0,0,0 | " + spec     # Rainmeter fills every path white unless told otherwise
        self._add(("path", d + (" | ClosePath 1" if closed else ""), spec, gradient))

    def poly(self, geom, spec, gradient=None):
        for p in polys_of(geom):
            for q in hole_free(p):
                if q.area > 2:
                    self.path(list(q.exterior.coords)[:-1], spec, True, gradient)

    def line(self, geom, spec):
        for ln in lines_of(geom):
            self.path(list(ln.coords), spec)

    def raw(self, spec):
        self._add(("raw", None, spec, None))

    def ellipse(self, x, y, rx, ry, spec):
        self.raw(f"Ellipse {x:.1f},{y:.1f},{rx:.1f},{ry:.1f} | {spec}")

    def rect(self, x, y, w, h, spec, r=0):
        self.raw(f"Rectangle {x:.1f},{y:.1f},{w:.1f},{h:.1f}{',%.1f' % r if r else ''} | {spec}")

    def __len__(self):
        return len(self.items)

    def write(self, folder=None):
        chunks = [self.items[i:i + PER_METER] for i in range(0, len(self.items), PER_METER)] or [[]]
        out = []
        for n, chunk in enumerate(chunks, 1):
            name = self.name if len(chunks) == 1 else f"{self.name}{n:02d}"
            lines = [f"[{name}]", "Meter=Shape", "X=0", "Y=0"]
            if not chunk:
                lines.append("Shape=Rectangle 0,0,0,0 | Fill Color 0,0,0,0 | StrokeWidth 0")
            for k, (kind, d, spec, gradient) in enumerate(chunk, 1):
                key = "Shape" if k == 1 else f"Shape{k}"
                if gradient:
                    lines.append(f"G{k}={gradient}")
                    spec = spec.replace("{G}", f"G{k}")
                if kind == "path":
                    lines.append(f"P{k}={d}")
                    lines.append(f"{key}=Path P{k} | {spec}")
                else:
                    lines.append(f"{key}={spec}")
            lines.append("TransformationMatrix=#Scale#;0;0;#Scale#;0;0")
            if self.hidden:
                lines.append(f"Hidden={self.hidden}")
            lines.append("DynamicVariables=0")
            out.append("\n".join(lines) + "\n")
        (folder or PARTS).mkdir(parents=True, exist_ok=True)
        ((folder or PARTS) / f"{self.name}.inc").write_text(HEADER + "\n".join(out), newline="\r\n")
        return len(self.items)


def sym_poly(layer, geom, spec, angle=None, stops=None):
    """left-side polygon + its mirror; a gradient angle is mirrored with it"""
    layer.poly(geom, spec, grad(angle, *stops) if stops else None)
    layer.poly(mirror(geom), spec, grad(180 - angle, *stops) if stops else None)


def sym_path(layer, pts, spec, closed=False):
    layer.path(pts, spec, closed)
    layer.path(mpts(pts), spec, closed)


# ------------------------------------------------------------------ the ship
SCREEN = box(0, 0, CW, CH)
BEZELS = unary_union([cpoly(b) for b in R.BEZELS])
# glass = the drawn windows minus the rounded visor bezels at the four corners
GLASS = [g for w in R.WINDOWS for g in polys_of(cpoly(w).difference(BEZELS)) if g.area > 50]
WINDOWS = unary_union(GLASS)
HULL = SCREEN.difference(WINDOWS)
ZONES = {z["id"]: Polygon(z["quad"]) for z in R.ZONES}
BUSY = unary_union(list(ZONES.values()) + [Point(*C([l])[0]).buffer(60) for l in R.LIGHTS]).buffer(10)

PILLAR = cpoly(R.PILLAR_L)
STRUT = cpoly(R.STRUT_L)
SILL_EDGE = C(R.SILL_EDGE_L)
# centre console (trapezoid widening to the floor) and the cowl under the windscreen
COWL = cpoly([(500.8, 365.5), (759.2, 365.5), (776, 393), (484, 393)])
CONSOLE = cpoly([(484, 393), (776, 393), (905, 709), (355, 709)])


def member_axis(poly_pts, a, b):
    A, B = C([a])[0], C([b])[0]
    ax = norm(B[0] - A[0], B[1] - A[1])
    return A, B, ax, (-ax[1], ax[0])


def cylinder(angle):
    """stops for a rounded metal member: dark edges, bright ridge a little off-centre"""
    return grad(angle, (f"{DARK},255", 0), (f"{MID},255", 0.28), (f"{LIGHT},255", 0.42), (f"{MID},255", 0.62), (f"{DARK},255", 1))


def build():
    rng = random.Random(11)
    # baked into hull.png by tools/frame_render.py; their theme-coloured shapes go to the live Accents layer
    accents = Layer("Accents", hidden=VECTOR_ONLY)
    hull = Layer("Hull", redirect=accents)
    frames = Layer("Frames", redirect=accents)
    greeb = Layer("Greebles", redirect=accents)
    # live Shape meters
    lights = Layer("Lights", hidden=VECTOR_ONLY)
    spill = Layer("Spill")
    glass = Layer("Glass")
    decor = Layer("Decor")

    # ---------------------------------------------------------------- glass
    for g in GLASS:
        glass.poly(g, "Fill LinearGradient GlassGrad | StrokeWidth 0")

    # ---------------------------------------------------------------- hull: silhouette, then shaded members
    hull.poly(HULL, "Fill LinearGradient {G} | StrokeWidth 0",
              grad(90, (f"{DARK},255", 0), (f"{MID},255", 0.5), (f"{DARK},255", 1)))
    left = box(0, 0, CW / 2, CH)
    # ceiling band: darker up top, catching light toward the windscreen
    ceil = box(0, 0, CW / 2, 106 * R.SY + 2).intersection(HULL).difference(STRUT)
    sym_poly(hull, ceil, "Fill LinearGradient {G} | StrokeWidth 0", 90,
             [(f"{DARK},255", 0), (f"{DARK},255", 0.6), (f"{MID},255", 1)])
    # A-pillar and roof strut, shaded as rounded members across their width
    for pts, a, b in ((R.PILLAR_L, (279.6, 97), (489, 371.5)), (R.STRUT_L, (180, 63), (0, 242))):
        A, B, ax, n = member_axis(pts, a, b)
        g, ang = cpoly(pts).intersection(HULL), math.degrees(math.atan2(n[1], n[0]))
        hull.poly(g, "Fill LinearGradient {G} | StrokeWidth 0", cylinder(ang))
        hull.poly(mirror(g), "Fill LinearGradient {G} | StrokeWidth 0", cylinder(180 - ang))
    # side wall below the side window: bands running parallel to the sill
    e0, e1 = SILL_EDGE[0], SILL_EDGE[1]
    sx, sy = norm(e1[0] - e0[0], e1[1] - e0[1])
    sn = (-sy, sx)                                                # normal pointing down into the wall
    if sn[1] < 0:
        sn = (-sn[0], -sn[1])
    wall = HULL.intersection(left).difference(CONSOLE).difference(COWL).difference(PILLAR)
    wall = wall.difference(Polygon([(0, 0), (CW / 2, 0), (CW / 2, e1[1]), e1, e0, (0, e0[1])]))
    sill_ang = math.degrees(math.atan2(sn[1], sn[0]))
    bands = [(0, 30, [(f"{LIGHT},255", 0), (f"{MID},255", 0.45), (f"{DARK},255", 1)]),        # lit sill top
             (30, 150, [(f"{MID},255", 0), (f"{DARK},255", 1)]),                                # upper wall panel
             (150, 290, [(f"{DARK},255", 0), (f"{MID},235", 0.5), (f"{DARK},255", 1)]),          # lower wall panel
             (290, 900, [(f"{DARK},255", 0), (f"0,0,0,255", 1)])]                               # floor shadow
    band_lines = []
    for d0, d1, stops in bands:
        strip = Polygon([(e0[0] - sx * 3000 + sn[0] * d0, e0[1] - sy * 3000 + sn[1] * d0),
                         (e0[0] + sx * 3000 + sn[0] * d0, e0[1] + sy * 3000 + sn[1] * d0),
                         (e0[0] + sx * 3000 + sn[0] * d1, e0[1] + sy * 3000 + sn[1] * d1),
                         (e0[0] - sx * 3000 + sn[0] * d1, e0[1] - sy * 3000 + sn[1] * d1)])
        sym_poly(hull, wall.intersection(strip), "Fill LinearGradient {G} | StrokeWidth 0", sill_ang, stops)
        if d0 > 0:
            band_lines.append(d0)
    # console and cowl
    hull.poly(CONSOLE, "Fill LinearGradient {G} | StrokeWidth 0",
              grad(90, (f"{MID},255", 0), (f"{DARK},255", 0.55), (f"0,0,0,255", 1)))
    hull.poly(COWL, "Fill LinearGradient {G} | StrokeWidth 0",
              grad(90, (f"{LIGHT},255", 0), (f"{MID},255", 0.4), (f"{DARK},255", 1)))
    # console side bevels
    for pts in (C([(484, 393), (355, 709)]), ):
        sym_path(hull, pts, f"Stroke Color {LIGHT},150 | StrokeWidth 2.2")
        sym_path(hull, [(x + 6, y) for x, y in pts], "Stroke Color 0,0,0,170 | StrokeWidth 3")
    hull.path(C([(484, 393), (776, 393)]), "Stroke Color 0,0,0,180 | StrokeWidth 3")
    hull.path(C([(500.8, 366.5), (759.2, 366.5)]), f"Stroke Color {EDGE},170 | StrokeWidth 2")
    # wall seams between the bands (groove + lit lip), clipped off widgets
    for d in band_lines[:2]:
        ln = LineString([(e0[0] - sx * 3000 + sn[0] * d, e0[1] - sy * 3000 + sn[1] * d),
                         (e0[0] + sx * 3000 + sn[0] * d, e0[1] + sy * 3000 + sn[1] * d)]).intersection(wall)
        for seg in lines_of(ln):
            pts = list(seg.coords)
            sym_path(hull, pts, "Stroke Color 0,0,0,190 | StrokeWidth 3")
            sym_path(hull, [(x + sn[0] * 2.5, y + sn[1] * 2.5) for x, y in pts], f"Stroke Color {LIGHT},110 | StrokeWidth 1.2")

    # wall panel cuts across the bands, each with a pair of rivets
    for along in range(260, 1100, 290):
        p0, p1 = (e0[0] + sx * along + sn[0] * 34, e0[1] + sy * along + sn[1] * 34), (e0[0] + sx * along + sn[0] * 290, e0[1] + sy * along + sn[1] * 290)
        seg = LineString([p0, p1]).intersection(wall.buffer(-8)).difference(BUSY)
        for s_ in lines_of(seg):
            pts = list(s_.coords)
            sym_path(hull, pts, "Stroke Color 0,0,0,180 | StrokeWidth 2.6")
            sym_path(hull, [(x + 2.2, y) for x, y in pts], f"Stroke Color {LIGHT},70 | StrokeWidth 1")

    # ---------------------------------------------------------------- window edges (owner's crops): a tube rail along
    # the glass, a thin second rail, two cables sagging between clamps, a red strip under the side-window sills;
    # no bolts. Not on edges that lie on the screen border or under the corner pieces.
    excl = SCREEN.difference(SCREEN.buffer(-4)).union(BEZELS.buffer(8))

    def rail(k):
        out = []
        for wp in GLASS:
            ring = wp.buffer(k, join_style=2).exterior.difference(excl)
            out += [(wp, ln) for ln in lines_of(ring) if ln.length > 30]
        return out

    for wp, ln in rail(7):
        pts = list(ln.coords)
        frames.path(pts, "Stroke Color 0,0,0,230 | StrokeWidth 15 | StrokeLineJoin Round")
        frames.path(pts, f"Stroke Color {MID},255 | StrokeWidth 11 | StrokeLineJoin Round")
    for wp, ln in rail(4.5):
        frames.path(list(ln.coords), f"Stroke Color {LIGHT},255 | StrokeWidth 2.6 | StrokeLineJoin Round")
    for wp, ln in rail(2.2):
        frames.path(list(ln.coords), f"Stroke Color {EDGE},70 | StrokeWidth 1 | StrokeLineJoin Round")
    for wp, ln in rail(19):
        pts = list(ln.coords)
        frames.path(pts, "Stroke Color 0,0,0,210 | StrokeWidth 6 | StrokeLineJoin Round")
        frames.path(pts, f"Stroke Color {MID},255 | StrokeWidth 3 | StrokeLineJoin Round")
    # cables: sample along the rail, sag outward between clamps every 150 px
    for k, amp in ((12, 3.5), (26, 5)):
        for wp, ln in rail(k):
            outer = wp.buffer(k + 1)
            pts, d = [], 0.0
            while d <= ln.length:
                p, q = ln.interpolate(d), ln.interpolate(min(ln.length, d + 2))
                tx, ty = norm(q.x - p.x, q.y - p.y)
                nx, ny = -ty, tx
                if outer.contains(Point(p.x + nx * 3, p.y + ny * 3)):
                    nx, ny = -nx, -ny
                sag = amp * math.sin(math.pi * (d % 150) / 150)
                pts.append((p.x + nx * sag, p.y + ny * sag))
                d += 6
            frames.path(pts, "Stroke Color 3,4,6,255 | StrokeWidth 2.6 | StrokeLineJoin Round")
            frames.path([(x, y - 1) for x, y in pts], f"Stroke Color {LIGHT},70 | StrokeWidth 0.8")
    # clamps across the rails where the cables are tied
    for wp, ln in rail(14):
        d = 75.0
        while d < ln.length - 20:
            p, q = ln.interpolate(d), ln.interpolate(d + 2)
            tx, ty = norm(q.x - p.x, q.y - p.y)
            nx, ny = -ty, tx
            a_, b_ = (p.x - nx * 12, p.y - ny * 12), (p.x + nx * 15, p.y + ny * 15)
            frames.path([a_, b_], "Stroke Color 0,0,0,230 | StrokeWidth 7")
            frames.path([a_, b_], f"Stroke Color {LIGHT},255 | StrokeWidth 3")
            d += 150
    # red accent strip under the side-window rails (second crop)
    for pts in (C(R.SILL_EDGE_L), mpts(C(R.SILL_EDGE_L))):
        strip = LineString([(x, y + 36) for x, y in pts]).difference(excl).intersection(HULL.buffer(-2))
        frames.line(strip, "Stroke Color 150,26,30,210 | StrokeWidth 3")
        frames.line(strip, "Stroke Color 255,90,90,60 | StrokeWidth 1")
    # lamp housings at the strut lights: a pale cylinder along the nearest edge, dark band, lens socket
    edges = unary_union([g.exterior for g in GLASS])
    for (x, y) in R.LIGHTS:
        X, Y = x * R.SX, y * R.SY
        np_ = edges.interpolate(edges.project(Point(X, Y)))
        q = edges.interpolate(edges.project(Point(X, Y)) + 4)
        tx, ty = norm(q.x - np_.x, q.y - np_.y)
        nx, ny = -ty, tx
        L2, W2 = 46, 25
        body = [(X - tx * L2 - nx * W2, Y - ty * L2 - ny * W2), (X + tx * L2 - nx * W2, Y + ty * L2 - ny * W2),
                (X + tx * L2 + nx * W2, Y + ty * L2 + ny * W2), (X - tx * L2 + nx * W2, Y - ty * L2 + ny * W2)]
        ang = math.degrees(math.atan2(ny, nx))
        frames.path(body, "Fill LinearGradient {G} | Stroke Color 0,0,0,230 | StrokeWidth 2", True,
                    grad(ang, ("50,56,64,255", 0), ("205,212,220,255", 0.35), ("130,140,152,255", 0.7), ("36,40,46,255", 1)))
        band = [(X + tx * (L2 - 12) - nx * W2, Y + ty * (L2 - 12) - ny * W2), (X + tx * L2 - nx * W2, Y + ty * L2 - ny * W2),
                (X + tx * L2 + nx * W2, Y + ty * L2 + ny * W2), (X + tx * (L2 - 12) + nx * W2, Y + ty * (L2 - 12) + ny * W2)]
        frames.path(band, "Fill Color 12,14,18,255 | StrokeWidth 0", True)
        frames.ellipse(X, Y, 19, 19, "Fill Color 225,230,236,255 | Stroke Color 30,34,40,255 | StrokeWidth 2")
        frames.ellipse(X, Y, 12, 12, "Fill Color 6,12,22,255 | Stroke Color 90,100,112,255 | StrokeWidth 1.5")

    # ---------------------------------------------------------------- visor bezels: the rounded corner cut-offs
    # baked: a dark rolled lip just outside the rim; live (Accents): blue light bleeding off the rim edge
    # (the corner pieces themselves are baked by frame_render.corners_png and drawn over the mist)

    # ---------------------------------------------------------------- pillar / strut detail
    members = [(R.PILLAR_L, (279.6, 97), (489, 371.5), (0.2, 0.62, 0.86), (0.7, 0.8)),
               (R.STRUT_L, (180, 63), (0, 242), (0.3, 0.75), None)]
    for pts, a, b, seams, vent in members:
        poly = cpoly(pts).intersection(HULL)
        A, B, ax, n = member_axis(pts, a, b)
        for side in (0, 1):
            P_ = poly if side == 0 else mirror(poly)
            A_ = A if side == 0 else (CW - A[0], A[1])
            B_ = B if side == 0 else (CW - B[0], B[1])
            ax_ = ax if side == 0 else (-ax[0], ax[1])
            n_ = n if side == 0 else (-n[0], n[1])
            for off, spec in ((-24, "Stroke Color 0,0,0,130 | StrokeWidth 1.8"), (-25.8, f"Stroke Color {LIGHT},45 | StrokeWidth 0.8")):
                for p in polys_of(P_.buffer(off, join_style=2)):
                    greeb.line(p.exterior.difference(BUSY), spec)
            for t in seams:
                c = at(A_, B_, t)
                seg = LineString([(c[0] - n_[0] * 400, c[1] - n_[1] * 400), (c[0] + n_[0] * 400, c[1] + n_[1] * 400)]).intersection(P_.buffer(-14))
                for s in lines_of(seg):
                    if s.intersects(BUSY):
                        continue
                    p0, p1 = s.coords[0], s.coords[-1]
                    greeb.path([p0, p1], "Stroke Color 0,0,0,190 | StrokeWidth 2.6")
                    greeb.path([(p0[0] + ax_[0] * 2.4, p0[1] + ax_[1] * 2.4), (p1[0] + ax_[0] * 2.4, p1[1] + ax_[1] * 2.4)],
                               f"Stroke Color {LIGHT},90 | StrokeWidth 1")
            if vent:
                c0, c1 = at(A_, B_, vent[0]), at(A_, B_, vent[1])
                plate = P_.buffer(-28).intersection(LineString([c0, c1]).buffer(40, cap_style=2))
                if plate.geom_type == "Polygon" and not plate.intersects(BUSY) and plate.area > 200:
                    greeb.poly(plate, "Fill Color 0,0,0,110 | Stroke Color 0,0,0,180 | StrokeWidth 1.4")
                    m = max(4, int(math.dist(c0, c1) / 10))
                    for i in range(m):
                        c = at(c0, c1, (i + 0.5) / m)
                        seg = LineString([(c[0] - n_[0] * 200, c[1] - n_[1] * 200), (c[0] + n_[0] * 200, c[1] + n_[1] * 200)]).intersection(plate.buffer(-5))
                        for s in lines_of(seg):
                            p0, p1 = s.coords[0], s.coords[-1]
                            greeb.path([p0, p1], "Stroke Color 0,0,0,230 | StrokeWidth 3.4 | StrokeStartCap Round | StrokeEndCap Round")
                            greeb.path([(p0[0] + ax_[0] * 2.4, p0[1] + ax_[1] * 2.4), (p1[0] + ax_[0] * 2.4, p1[1] + ax_[1] * 2.4)],
                                       f"Stroke Color {LIGHT},60 | StrokeWidth 1")

    # ---------------------------------------------------------------- side walls: grab handles, LED clusters, vents
    def wall_point(d_along, d_down):
        return (e0[0] + sx * d_along + sn[0] * d_down, e0[1] + sy * d_along + sn[1] * d_down)

    def handle(p0, p1):
        for side in (0, 1):
            q0, q1 = (p0, p1) if side == 0 else ((CW - p0[0], p0[1]), (CW - p1[0], p1[1]))
            bar = [q0, q1]
            greeb.path(bar, "Stroke Color 0,0,0,170 | StrokeWidth 15 | StrokeStartCap Round | StrokeEndCap Round")
